"""Check that tracked files carry an SPDX licence header (P0.1-T3).

Lists tracked files with ``git ls-files`` and fails (exit 1) when a file that needs a header lacks
``SPDX-License-Identifier: MIT`` in its first five lines, or has an unknown file type.
"""

from __future__ import annotations

import re
import subprocess
import sys
from pathlib import Path, PurePosixPath

HEADER_LINES = 5
IDENTIFIER = "SPDX-License-Identifier: MIT"

# After the comment marker (any run of non-word characters such as "//", "#", "/*" or ";"), the
# line must read exactly the identifier, then optional whitespace, an optional block-comment
# closer and end of line. "MIT-0" and "MIT OR Apache-2.0" therefore fail.
IDENTIFIER_LINE = re.compile(r"^\s*(?:[^\w\s]+\s*)?" + re.escape(IDENTIFIER) + r"\s*(?:\*/)?\s*$")

# Extensions that need our header.
HEADED_SUFFIXES = frozenset(
    {
        ".c", ".cc", ".cpp", ".cxx", ".h", ".hh", ".hpp", ".hxx", ".inl",
        ".cmake", ".py", ".sh", ".ps1", ".yml", ".yaml", ".toml",
    }
)  # fmt: skip

# Exact file names that need our header.
HEADED_NAMES = frozenset(
    {
        "CMakeLists.txt", ".clang-format", ".clang-tidy", ".editorconfig",
        ".gitattributes", ".gitignore", "CODEOWNERS",
    }
)  # fmt: skip

# Exempt by suffix, each with the reason.
EXEMPT_SUFFIXES = {
    ".md": "Markdown has no comment syntax we rely on",
    ".json": "JSON has no comment syntax (covers CMakePresets.json)",
}

# Exempt by exact file name, each with the reason.
EXEMPT_NAMES = {
    "LICENSE": "licence text itself",
    "uv.lock": "generated by uv",
    ".python-version": "single-line tool file without comment syntax",
    ".gitkeep": "empty placeholder",
}

# Vendored third-party files: path -> text that must appear in the first lines instead of ours.
VENDORED = {
    "cmake/CPM.cmake": "MIT License",
}

EXEMPT_DIRS = {
    "data": "binary blobs under Git LFS",
}

# How many lines of a vendored file are searched for its own licence marker.
VENDORED_LINES = 10


def tracked_files(root: Path) -> list[str]:
    """Return the tracked file paths (POSIX style) relative to ``root``."""
    out = subprocess.run(
        ["git", "ls-files", "-z"], cwd=root, check=True, capture_output=True
    ).stdout.decode()
    return [p for p in out.split("\0") if p]


def head_lines(path: Path, count: int) -> list[str] | None:
    """Return the first ``count`` lines, or None when the file is binary."""
    data = path.read_bytes()
    if b"\0" in data:
        return None
    return data.decode("utf-8", errors="replace").splitlines()[:count]


def check_file(root: Path, rel: str) -> str | None:
    """Return a problem description for ``rel``, or None when it is fine."""
    pure = PurePosixPath(rel)
    path = root / rel
    if rel in VENDORED:
        lines = head_lines(path, VENDORED_LINES)
        if lines is None or not any(VENDORED[rel] in line for line in lines):
            return f"vendored file lacks its own licence marker '{VENDORED[rel]}'"
        return None
    if pure.parts[0] in EXEMPT_DIRS:
        return None
    if pure.name in EXEMPT_NAMES or pure.suffix in EXEMPT_SUFFIXES:
        return None
    if path.stat().st_size == 0:
        return None
    lines = head_lines(path, HEADER_LINES)
    if lines is None:
        return None  # binary
    if pure.name not in HEADED_NAMES and pure.suffix not in HEADED_SUFFIXES:
        return "unknown file type (add it to tools/check_spdx.py as headed or exempt)"
    if not any(IDENTIFIER_LINE.match(line) for line in lines):
        return f"missing '{IDENTIFIER}' in the first {HEADER_LINES} lines"
    return None


def run(root: Path) -> list[str]:
    """Check every tracked file under ``root``; return one message per problem."""
    problems: list[str] = []
    for rel in tracked_files(root):
        if not (root / rel).is_file():
            continue  # deleted in the working tree
        problem = check_file(root, rel)
        if problem is not None:
            problems.append(f"{rel}: {problem}")
    return problems


def main() -> int:
    """Entry point; the repository root is the parent of this script's directory."""
    root = Path(__file__).resolve().parent.parent
    problems = run(root)
    for line in problems:
        print(line, file=sys.stderr)
    if problems:
        print(f"{len(problems)} file(s) failed the SPDX check", file=sys.stderr)
        return 1
    print("SPDX check passed")
    return 0


if __name__ == "__main__":
    sys.exit(main())
