"""Extract Appendix A of HAL hal-00688679v2; requires pdftotext (Poppler).

Usage: python3 extract_parameters.py /path/to/report.pdf
Writes source CSV and the compiled-in table next to this script. No network access.
The original PDF is not redistributed. Values retain the appendix's rounding.
"""
import csv
import hashlib
from pathlib import Path
import re
import subprocess
import sys

FIELDS = [
    ("f0", "frequency_hz"), ("L", "length_m"), ("d", "diameter_mm"),
    ("ρ", "effective_density_kg_m3"), ("T0", "tension_n"),
    ("Ru", "transverse_loss_per_s"), ("ηu", "transverse_viscosity_s"),
    ("p", "felt_exponent"), ("xH", "strike_m"), ("MH", "hammer_mass_g"),
    ("KH", "felt_stiffness"), ("RH", "felt_dissipation"),
]

def numbers(line):
    # pdftotext renders 5.840 × 10^09 as "5.840 × 1009".
    line = re.sub(r"([\d.]+)\s*×\s*10([−-]?\d+)",
                  lambda m: m[1] + "e" + m[2].replace("−", "-"), line)
    return [float(x) for x in line.split()]

def main():
    pdf = Path(sys.argv[1])
    raw = subprocess.check_output(["pdftotext", "-layout", str(pdf), "-"], text=True)
    # Select appendix A by its heading, not the table of contents.
    raw = re.split(r"\nA\s+Wrapped strings values\s*\n", raw)[1]
    raw = re.split(r"\nB\s+Unwrapped strings values\s*\n", raw)[0]
    rows = []
    pending = None
    for line in raw.splitlines():
        if re.match(r"\s*Note\s+", line):
            names = line.split()[1:]
            pending = [{"midi_key": 24 + len(rows) + i, "source_note": n}
                       for i, n in enumerate(names)]
            rows.extend(pending)
        elif pending:
            for symbol, field in FIELDS:
                match = re.match(r"\s*" + re.escape(symbol) + r"\s+\([^)]*\)\s+(.+)$", line)
                if match:
                    values = numbers(match[1])
                    assert len(values) == len(pending), (field, values)
                    for row, value in zip(pending, values): row[field] = value
    assert len(rows) == 84, len(rows)
    assert all(len(r) == len(FIELDS) + 2 for r in rows)
    assert rows[36]["source_note"] == "C4" and rows[36]["diameter_mm"] == 1.006
    directory = Path(__file__).resolve().parent
    columns = ["midi_key", "source_note"] + [f for _, f in FIELDS]
    with (directory / "report-appendix-a.csv").open("w", newline="") as out:
        writer = csv.DictWriter(out, fieldnames=columns, lineterminator="\n")
        writer.writeheader(); writer.writerows(rows)
    fields = [f for _, f in FIELDS]
    header = ["// SPDX-License-Identifier: MIT",
              "// Generated by extract_parameters.py from HAL hal-00688679v2 Appendix A.",
              "// PDF SHA256: " + hashlib.sha256(pdf.read_bytes()).hexdigest(),
              "#pragma once", "#include <array>", "namespace piano_mvp_v2 {",
              "struct ReportRow {", "    int midi_key;"]
    header += ["    double " + f + ";" for f in fields]
    header += ["};", "inline constexpr std::array<ReportRow, 84> kReportRows{{"]
    header += ["    {" + str(r["midi_key"]) + ", " + ", ".join(repr(r[f]) for f in fields) + "},"
               for r in rows]
    header += ["}};", "}", ""]
    (directory / "report_parameters.hpp").write_text("\n".join(header))
    print("Extracted 84 rows, C1–B7, from Appendix A; generated CSV and C++ table.")

if __name__ == "__main__": main()
