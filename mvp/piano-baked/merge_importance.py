"""Merge piano-baked-select energy files into baked_importance.hpp.
Each scenario is normalised to unit total energy; the importance of a mode is its largest normalised share over
the scenarios blended with the mean (so a mode that matters in one scenario is not averaged away)."""
import sys, numpy as np
out, files = sys.argv[1], sys.argv[2:]
E = []
for f in files:
    e = np.loadtxt(f)
    E.append(e / e.sum())
E = np.array(E)
imp = 0.5 * E.max(0) + 0.5 * E.mean(0)
imp /= imp.sum()
imp[imp < 1e-16] = 0.0
with open(out, 'w') as f:
    f.write('// SPDX-License-Identifier: MIT\n// Generated by merge_importance.py from piano-baked-select energies (Full, modal radiation):\n'
            '// fraction of the radiated energy per board mode, blended over the training scenarios. Not edited by hand.\n'
            '#pragma once\n#include <array>\nnamespace piano_mvp_v4 {\ninline constexpr std::array<double,512> kBakedImportance{{\n')
    for i in range(0, 512, 4):
        f.write('    ' + ', '.join('%.17g' % v for v in imp[i:i+4]) + ',\n')
    f.write('}};\n}\n')
srt = np.sort(imp)
c = np.cumsum(srt)
for tol in [1e-10, 1e-9, 3e-9, 1e-8, 1e-7, 1e-6, 1e-5]:
    print('tol %.0e: keeps %d modes' % (tol, (c > tol).sum()))
