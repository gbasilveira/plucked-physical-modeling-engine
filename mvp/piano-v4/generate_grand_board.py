"""Emit the (m, n) index of every row of the MVP 3 soundboard table (0.5.1).

The MVP 3 table (piano-v3/soundboard_table.hpp, generate_soundboard.py) lists the 512 lowest
modes of a simply supported orthotropic plate with homogenised ribs, but not their indices.
Mode shapes are phi_mn(x,y) = N sin(m pi x/lx) sin(n pi y/ly), so a mode's participation at an
arbitrary bridge point needs (m, n). This script re-derives the same ordering with the same
formulas and checks every omega against the MVP 3 table (relative 1e-12) before writing
grand_board_table.hpp. NumPy only. Run: python3 generate_grand_board.py
"""
from pathlib import Path
import math
import re

HERE = Path(__file__).resolve().parent

def modes():
    lx, ly, h, rho = 1.4, 1.6, 0.008, 390.0
    ex, ey, gxy, nu = 11.6e9, 0.9e9, 0.75e9, 0.37
    denom = 1 - nu * nu * ey / ex
    dx, dy = ex*h**3/(12*denom), ey*h**3/(12*denom)
    dxy, d66 = nu*ey*h**3/(12*denom), gxy*h**3/12
    mu = rho*h
    rw, rh, pitch = 0.025, 0.025, 0.14
    ap, ar = pitch*h, rw*rh
    zp, zr = h/2, h+rh/2
    neutral = (ey*ap*zp + ex*ar*zr)/(ey*ap + ex*ar)
    composite = (ey*(pitch*h**3/12 + ap*(zp-neutral)**2) + ex*(rw*rh**3/12 + ar*(zr-neutral)**2))/pitch
    dy += composite - ey*h**3/12
    mu += rho*ar/pitch
    out = []
    for m in range(1, 33):
        for n in range(1, 41):
            kx, ky = math.pi*m/lx, math.pi*n/ly
            omega = math.sqrt((dx*kx**4 + 2*(dxy+2*d66)*kx*kx*ky*ky + dy*ky**4)/mu)
            out.append((omega, m, n))
    out.sort()
    return out[:512], lx, ly, mu

def main():
    rows, lx, ly, mu = modes()
    text = (HERE.parent/'piano-v3'/'soundboard_table.hpp').read_text()
    table = [float(m.group(1)) for m in re.finditer(r'^\s*\{([-0-9.e+]+),', text, re.M)]
    assert len(table) == 512
    for (omega, m, n), ref in zip(rows, table):
        assert abs(omega/ref - 1) < 1e-12, (m, n, omega, ref)
    lines = ["// SPDX-License-Identifier: MIT",
             "// Generated by generate_grand_board.py; (m, n) of each MVP 3 soundboard-table row.",
             "// Plate: simply supported orthotropic spruce with homogenised ribs (nominal, not measured).",
             "#pragma once", "#include <array>", "#include <cstdint>",
             "namespace piano_mvp_v4 {",
             f"inline constexpr double kBoardLx = {lx!r}, kBoardLy = {ly!r};",
             f"inline constexpr double kBoardMu = {mu!r};  // effective areal density incl. rib mass, kg/m^2",
             "inline constexpr std::array<std::array<std::uint8_t, 2>, 512> kBoardModeIndex{{"]
    lines += [f"    {{{m}, {n}}}," for _, m, n in rows]
    lines += ["}};", "}", ""]
    (HERE/'grand_board_table.hpp').write_text("\n".join(lines))
    print('ok', len(rows), 'modes; mu =', mu)

if __name__ == '__main__': main()
