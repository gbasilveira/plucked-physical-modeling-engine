"""Generate an orthotropic spruce plate with homogenised ribs and radiation table.

Material: Chabassier & Duruflé RT-0425 v2, section 2.1, first spruce row.
Geometry/boundary/loss/listening positions are experiment assumptions, not measurements.
Requires NumPy only. Run from any directory; output is beside this script.
"""
from pathlib import Path
import json
import math
import numpy as np

def generate():
    lx, ly, h, rho = 1.4, 1.6, 0.008, 390.0
    ex, ey, gxy, nu = 11.6e9, 0.9e9, 0.75e9, 0.37
    rho_air, speed, reference_distance = 1.2, 343.0, 1.5
    loss_factor = 0.02
    denom = 1 - nu * nu * ey / ex
    dx = ex * h**3 / (12 * denom)
    dy = ey * h**3 / (12 * denom)
    dxy = nu * ey * h**3 / (12 * denom)
    d66 = gxy * h**3 / 12
    mu = rho * h
    # Nominal periodic ribs parallel to y. Composite neutral-axis bending per pitch
    # is homogenised into Dy; this is not an explicit ribbed FEM board.
    rib_width, rib_height, rib_pitch = 0.025, 0.025, 0.14
    ap, ar = rib_pitch*h, rib_width*rib_height
    zp, zr = h/2, h+rib_height/2
    neutral = (ey*ap*zp + ex*ar*zr)/(ey*ap + ex*ar)
    composite = (ey*(rib_pitch*h**3/12 + ap*(zp-neutral)**2) +
                 ex*(rib_width*rib_height**3/12 + ar*(zr-neutral)**2))/rib_pitch
    dy += composite - ey*h**3/12
    mu += rho*ar/rib_pitch
    normal = 2 / math.sqrt(mu * lx * ly)
    bridges = [(0.42, 0.91), (0.97, 0.58)]
    microphones = [(0.2, 0.8, 1.5), (1.2, 0.8, 1.5)]
    # Midpoint quadrature over the plate; 96 x 112 resolves the retained shapes.
    x = (np.arange(96) + 0.5) * lx / 96
    y = (np.arange(112) + 0.5) * ly / 112
    xx, yy = np.meshgrid(x, y, indexing="ij")
    distances = [np.sqrt((xx - a)**2 + (yy - b)**2 + z*z) for a,b,z in microphones]
    modes = []
    for m in range(1, 33):
        for n in range(1, 41):
            kx, ky = math.pi * m / lx, math.pi * n / ly
            omega = math.sqrt((dx*kx**4 + 2*(dxy+2*d66)*kx*kx*ky*ky + dy*ky**4)/mu)
            modes.append((omega,m,n))
    modes.sort()
    modes = modes[:512]
    rows = []
    for omega,m,n in modes:
        shape = normal*np.sin(m*math.pi*xx/lx)*np.sin(n*math.pi*yy/ly)
        drive = [normal*math.sin(m*math.pi*a/lx)*math.sin(n*math.pi*b/ly) for a,b in bridges]
        radiation = [rho_air/(2*math.pi) * lx*ly/(96*112) * np.sum(
            shape * np.exp(-1j*omega*(r-reference_distance)/speed)/r) for r in distances]
        rows.append([omega, 0.5*loss_factor*omega, *drive,
                     radiation[0].real,radiation[0].imag,radiation[1].real,radiation[1].imag])
    directory = Path(__file__).resolve().parent
    header = ["// SPDX-License-Identifier: MIT", "// Generated by generate_soundboard.py; nominal analytical plate, not measured data.",
              "#pragma once", "#include <array>", "namespace piano_mvp_v3 {",
              "inline constexpr double kRadiationDelaySeconds = 1.5 / 343.0;",
              "inline constexpr std::array<std::array<double, 8>, 512> kSoundboardModes{{"]
    header += ["    {" + ", ".join(format(v,'.17g') for v in row) + "}," for row in rows]
    header += ["}};", "}", ""]
    (directory/"soundboard_table.hpp").write_text("\n".join(header))
    metadata = dict(model="simply-supported orthotropic plate with homogenised ribs; approximate narrowband Rayleigh radiation",
                    measured=False, length_x_m=lx,length_y_m=ly,thickness_m=h,density_kg_m3=rho,
                    young_x_pa=ex,young_y_pa=ey,shear_xy_pa=gxy,poisson_xy=nu,loss_factor=loss_factor,
                    bridge_positions_m=bridges,microphone_positions_m=microphones,modes=len(rows),
                    minimum_frequency_hz=rows[0][0]/(2*math.pi),maximum_frequency_hz=rows[-1][0]/(2*math.pi),
                    radiation_delay_s=reference_distance/speed,quadrature=[96,112],
                    rib_width_m=rib_width,rib_height_m=rib_height,rib_pitch_m=rib_pitch,
                    effective_areal_density_kg_m2=mu,effective_dy_nm=dy)
    (directory/"soundboard-model.json").write_text(json.dumps(metadata,indent=2)+"\n")
    print(json.dumps(metadata))

if __name__ == "__main__": generate()
